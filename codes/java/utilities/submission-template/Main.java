import java.util.*;

public class Main {
    public static void main(String[] args) {
        Scanner sc;
        int a, b, ans;

        // 입력
        sc = new Scanner(System.in);
        a = sc.nextInt();
        b = sc.nextInt();

        // 계산
        ans = a + b;

        // 출력
        System.out.println(ans);
    }
}
